"""Write rust/src/errors_table.rs from the table of error codes (src/rabbit_brain/errors.py, which the SDK raises
with): each code, what it means and what to do about it. Run it after changing the table: python rust/gen/gen_errors.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "src"))
from rustlit import lit
from rabbit_brain.errors import ERRORS

OUT = os.path.join(HERE, "..", "src", "errors_table.rs")


def text() -> str:
    """The file's whole text, as the table gives it now."""
    out = ["// Generated by rust/gen/gen_errors.py from rabbit_brain/errors.py. The table of error codes: meaning and fix.", "",
           "pub static ERRORS: &[(&str, &str, &str)] = &["]
    for code, (meaning, fix) in ERRORS.items():
        out.append(f"    ({lit(code)}, {lit(meaning)}, {lit(fix)}),")
    out.append("];")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text())
    print(len(ERRORS), "codes")
