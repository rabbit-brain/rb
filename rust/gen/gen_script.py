"""Write rust/src/shell/assets/script.min.js, the page script rb page and rb open inline and rb export names by its
sha256, from rust/src/shell/assets/script.js: each whole-line comment taken out and each line's leading indentation,
nothing else (the orchestrator's ruling of Nov 12 07:05 +08, ASK-U2-SIZE.md option B). A line that starts inside a
template literal or a block comment is kept as written. A string or a regular expression that runs on past its line is
refused: the squeeze cannot tell where it ends. Run it after changing script.js: python rust/gen/gen_script.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src", "shell", "assets", "script.js")
OUT = os.path.join(HERE, "..", "src", "shell", "assets", "script.min.js")

HEAD = "// Generated by rust/gen/gen_script.py from script.js: its whole-line comments and indentation taken out.\n"
# what may stand before a regular expression's opening slash (else the slash divides)
BEFORE_REGEX = set("(,=:[!&|?{};+-*%~^<>") | {""}


class Unsqueezable(ValueError):
    pass


def _scan(line: str, state: list, n: int) -> None:
    """Walk one line, updating `state`: a stack whose top says where the next line starts ("code", "tpl" inside a
    template literal, "blk" inside a block comment); "code" frames inside a template's ${...} count their braces."""
    i, last = 0, ""
    while i < len(line):
        top = state[-1]
        c = line[i]
        if top[0] == "blk":
            j = line.find("*/", i)
            if j < 0:
                return
            state.pop()
            i = j + 2
            continue
        if top[0] == "tpl":
            if c == "\\":
                i += 2
                continue
            if c == "`":
                state.pop()
                last = "x"
                i += 1
                continue
            if line.startswith("${", i):
                state.append(["code", 0])
                i += 2
                continue
            i += 1
            continue
        # code
        if line.startswith("//", i):
            return
        if line.startswith("/*", i):
            state.append(["blk"])
            i += 2
            continue
        if c in "'\"":
            j = i + 1
            while j < len(line) and line[j] != c:
                j += 2 if line[j] == "\\" else 1
            if j >= len(line):
                raise Unsqueezable(f"script.js:{n}: a string runs on past its line")
            i, last = j + 1, "x"
            continue
        if c == "`":
            state.append(["tpl"])
            i += 1
            continue
        if c == "/" and last in BEFORE_REGEX:
            j, cls = i + 1, False
            while j < len(line) and (cls or line[j] != "/"):
                if line[j] == "\\":
                    j += 1
                elif line[j] == "[":
                    cls = True
                elif line[j] == "]":
                    cls = False
                j += 1
            if j >= len(line):
                raise Unsqueezable(f"script.js:{n}: a regular expression runs on past its line")
            i, last = j + 1, "x"
            continue
        if c == "{" and len(state) > 1:
            top[1] += 1
        elif c == "}" and len(state) > 1:
            if top[1] == 0:
                state.pop()
                last = "x"
                i += 1
                continue
            top[1] -= 1
        if not c.isspace():
            last = c if c in BEFORE_REGEX else "x"
            # a word before a slash: `return /x/` reads a regex, `a / b` divides
            if c.isalnum() or c in "_$)]":
                j = i
                while j < len(line) and (line[j].isalnum() or line[j] in "_$"):
                    j += 1
                word = line[i:j]
                last = "" if word in ("return", "typeof", "case", "in", "of", "else", "void", "do") else "x"
                i = max(j, i + 1)
                continue
        i += 1


def squeeze(src: str) -> str:
    out = []
    state = [["code", 0]]
    for n, line in enumerate(src.split("\n"), 1):
        where = state[-1][0]
        if where in ("tpl", "blk"):
            out.append(line)
        else:
            body = line.strip()
            if body.startswith("//") or not body:
                pass
            else:
                out.append(line.lstrip())
        _scan(line, state, n)
    if len(state) != 1:
        raise Unsqueezable("script.js ends inside a template literal or a block comment")
    return "\n".join(out) + "\n"


def text() -> str:
    with open(SRC, encoding="utf-8") as f:
        return HEAD + squeeze(f.read())


if __name__ == "__main__":
    t = text()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(t)
    with open(SRC, encoding="utf-8") as f:
        print(len(f.read().encode()), "->", len(t.encode()), "bytes")
