const fmt = (v: number) => v.toFixed(2);
const pct = (v: number) => `${Math.round(v * 100)}%`;
export function reportMarkdown(run: Comparison, limits: Limits, checks: SavedCheck[]) {
  const s = summary(run, limits);
  const withTrajectories = s.withTrajectories > 0;
  const row = (c: ComparisonCase) => {
    const stab = c.candidate_trajectory ? trajectoryStats(c.candidate_trajectory) : null;
    const base = `| ${c.id} | ${fmt(c.baseline_error)} | ${fmt(c.candidate_error)} | ${fmt(delta(c))} | ${outcome(c, limits.threshold)} |`;
    return withTrajectories ? `${base} ${stab ? `${pct(stab.lateShare)} · ${stab.reversals} rev.` : "n/a"} | ${stabilityOutcome(c, limits)} |` : base;
  };
  const unit = unitOf(run);
  return `# ${run.project}: model comparison\n\n${run.source === "example" ? "The worked example, not your own run: real output from a recorded comparison of two public checkpoints.\n\n" : "Imported evaluation results.\n\n"}Current: ${run.baseline}\nCandidate: ${run.candidate}\nDataset: ${run.dataset}\nMetric: ${metricLabel(run)} (${unit}), lower is better.\n\nMean of case errors: ${fmt(s.baseline)} → ${fmt(s.candidate)} ${unit}. Cases are weighted equally; this is not a pooled per-pixel mean.\nRegression threshold: increase greater than ${limits.threshold} ${unit}.\n${s.regressions} of ${run.cases.length} cases regress on error.\n${withTrajectories ? `Stability limits: late revision ≤ ${pct(limits.lateShare)}, reversals ≤ ${limits.reversals}. ${s.unstable} of ${s.withTrajectories} cases with trajectories are unstable; ${s.unstablePassing} of those pass on error.\n` : "No refinement trajectories were exported, so stability was not assessed.\n"}\n| Case | Current (${unit}) | Candidate (${unit}) | Change (${unit}) | Error |${withTrajectories ? " Candidate late revision | Stability |" : ""}\n|---|---:|---:|---:|---|${withTrajectories ? "---|---|" : ""}\n${rank(run.cases, limits).map(row).join("\n")}\n\n## Saved checks\n${checks.filter(c => c.project === run.project).map(c => `- ${c.id}: candidate error ≤ ${fmt(c.max_error)} ${unit}${c.max_late_share !== undefined ? `, late revision ≤ ${pct(c.max_late_share)}` : ""}: ${checkResult(c, run).status}`).join("\n") || "No saved checks for this project."}\n\nThe check runner evaluates these supplied metrics and trajectories against the limits. It does not run inference or certify a model for deployment.\n`;
}

