function frameSeries(mean: number, regression: boolean) {
  const shape = regression
    ? [.58, .63, .67, .70, .82, 1.06, 1.46, 1.75, 1.68, 1.57, 1.32, 1.04, .89, .80, .69, .64]
    : [.86, .90, .95, 1.06, 1.08, .98, 1.14, 1.16, 1.03, .94, 1.06, 1.01, .94, 1.04, .96, .89];
  const scale = mean / (shape.reduce((a, b) => a + b, 0) / shape.length);
  return shape.map(v => Number((v * scale).toFixed(3)));
}
// Update magnitude per refinement iteration (12 iterations). Shapes are scaled by the case's error so numbers vary.
function trajectoryShape(kind: Shape, error: number) {
  const shape = kind === "settled" ? [2.40, 1.52, .96, .63, .42, .29, .21, .15, .11, .08, .06, .05]
    : kind === "late" ? [2.30, 1.42, .90, .60, .43, .36, .31, .55, .84, .92, .78, .66]
    : [2.20, 1.30, .80, .55, .45, .42, .41, .44, .50, .58, .64, .70];
  const scale = 0.55 + error / 6;
  return shape.map(v => Number((v * scale).toFixed(3)));
}
